const copy = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;

/** L'incident de démonstration (une copie : l'interface peut la garder sans rien partager). */
export function demoIncident(): Incident {
  return copy(INCIDENT);
}

/** L'arborescence lisible du périmètre de démonstration. */
export function demoSourceTree(): SourceTree {
  return copy(TREE);
}

/** Les fichiers sources de la démonstration, par clé `application:fichier`. */
export function demoSources(): Record<string, SourceFileView> {
  return copy(SOURCES);
}

/** Un fichier de la démonstration ; absent : il n'est pas inclus dans les données de démonstration. */
export function demoSource(applicationId: string, file: string): SourceFileView | undefined {
  const view = SOURCES[`${applicationId}:${file}`];
  return view ? copy(view) : undefined;
}

/**
 * Le rapport de la démonstration, composé à partir des seules données de l'incident de démonstration
 * (comme le serveur le ferait), avec la limite qui le dit : ce n'est pas un rapport réel.
 */
export function demoReport(lang: 'fr' | 'en' = 'fr'): InvestigationReport {
  const incident = demoIncident();
  const investigation = incident.investigation;
  const reproduction = incidentReproduction(incident);
  const symbolIds = new Set(
    (investigation.graph?.nodes ?? []).flatMap((node) => (node.symbolId ? [node.symbolId] : [])),
  );
  const symbols = (investigation.code?.symbols ?? []).filter((symbol) => symbolIds.has(symbol.id));
  return {
    version: 1,
    generatedAt: incident.updatedAt,
    incident: {
      id: incident.id,
      projectId: incident.projectId,
      title: incident.title,
      description: incident.description,
      observed: incident.observed,
      expected: incident.expected,
      severity: incident.severity,
      state: incident.state,
    },
    environment: {
      execution: incident.execution,
      ...(incident.environmentId ? { environmentId: incident.environmentId } : {}),
      ...(reproduction?.baseUrl ? { baseUrl: reproduction.baseUrl } : {}),
    },
    scope: incident.scope,
    ...(incident.scenario ? { scenario: incident.scenario } : {}),
    timeline: (investigation.timeline ?? [])
      .filter((event) => event.reproduction === reproduction?.id)
      .map((event) => ({
        ...(event.at ? { at: event.at } : {}),
        ...(event.step !== undefined ? { step: event.step } : {}),
        kind: event.kind,
        summary: event.summary,
        ref: event.evidence[0] ?? event.id,
      })),
    requests: reproduction?.requests ?? [],
    code: {
      files: [...new Set(symbols.map((symbol) => symbol.file))],
      symbols,
      denied: investigation.code?.denied ?? [],
      truncated: investigation.code?.truncated ?? [],
    },
    ...(investigation.graph ? { graph: investigation.graph } : {}),
    hypotheses: investigation.hypotheses,
    experiments: investigation.experiments,
    ...(investigation.diagnosis ? { diagnosis: investigation.diagnosis } : {}),
    ...(investigation.regression ? { regression: investigation.regression } : {}),
    limitations: [
      lang === 'fr'
        ? 'Données de démonstration : un incident fictif, ce rapport n’est pas un diagnostic réel.'
        : 'Demonstration data: a fictional incident, this report is not a real diagnosis.',
    ],
  };
}
