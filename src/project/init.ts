import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { stringify } from 'yaml';
import { detectProject, type ProjectDetection } from './detect.js';
import { PROJECT_CONFIG_FILES, PROJECT_DIR, REPORTS_DIR } from './project-config.js';

/**
 * `qa-crawler init` : la configuration du projet et ses dossiers, à partir de la détection.
 * Jamais d'écrasement silencieux : une configuration existante est gardée (sauf `--force`), les
 * fichiers existants ne sont pas réécrits.
 */
export interface InitOptions {
  root: string;
  force?: boolean;
  baseUrl?: string;
  /** Un fichier d'exemple de flow est écrit dans qa-crawler/flows/. */
  example?: boolean;
}

export interface InitOutcome {
  detection: ProjectDetection;
  configFile: string;
  /** Fichiers et dossiers créés (chemins relatifs). */
  created: string[];
  /** Fichiers existants laissés tels quels. */
  kept: string[];
  notes: string[];
}

const DIRECTORIES = ['flows', 'actors', 'test-data', 'baselines', 'recordings', 'knowledge', 'memory'];

async function exists(file: string): Promise<boolean> {
  return stat(file).then(
    () => true,
    () => false,
  );
}

/** Le document qa-crawler.config.yaml proposé pour cette détection. */
export function renderProjectConfig(detection: ProjectDetection, baseUrl?: string): string {
  const config = {
    qaCrawler: {
      application: {
        baseUrl: baseUrl ?? detection.devUrl,
        startAt: '/',
        ...(detection.name ? { name: detection.name } : {}),
        framework: detection.framework,
      },
      browser: { browser: 'chromium', headless: true },
      ...(detection.playwright.config ? { playwright: { config: `./${detection.playwright.config}` } } : {}),
      recording: { enabled: true },
      replay: { enabled: true },
      exploration: { enabled: true },
      analysis: { enabled: true },
      api: { ...(detection.openapi ? { openapi: `./${detection.openapi}` } : {}), testing: true },
      visual: { enabled: false },
      staticAnalysis: { enabled: false, ...(detection.framework === 'angular' ? { source: '.' } : {}) },
      actors: [{ name: 'primary', primary: true, auth: { type: 'none' } }],
      intelligence: { enabled: false, mode: 'OFF', provider: 'copilot' },
      persistence: { enabled: true, provider: 'file' },
      reporting: { format: ['html', 'json'], language: 'en', failOnSeverity: 'ERROR', dir: REPORTS_DIR },
    },
  };
  const header = [
    '# QA-Crawler project configuration (generated by `qa-crawler init`).',
    '# Priority: command line > environment variables (QA_BASE_URL, QA_INTELLIGENCE_MODE, …) > this file > defaults.',
    '# Any mission key (safety, goals, oracles, gherkin, …) can be set under `qaCrawler.mission` and wins over the translation.',
    `# Flows live in ${PROJECT_DIR}/flows/ (YAML or .feature), reports in ${REPORTS_DIR}/.`,
    '# Credentials are never written here: actors use environment variables (usernameEnv / passwordEnv) and storageState files.',
    '',
  ].join('\n');
  return `${header}${stringify(config, { lineWidth: 0 })}`;
}

const EXAMPLE_FLOW = `# An imposed flow: delete or replace it with your own (or record one with \`qa-crawler record --name <flow>\`).
flows:
  - name: home-loads
    startAt: /
    steps:
      - expect: { url: / }
`;

const GITIGNORE = `# QA-Crawler: generated artifacts and learned data (never commit sessions)
${REPORTS_DIR}/
${PROJECT_DIR}/actors/*.json
${PROJECT_DIR}/memory/
${PROJECT_DIR}/knowledge/
${PROJECT_DIR}/baselines/
${PROJECT_DIR}/recordings/
${PROJECT_DIR}/.derived/
`;

export async function initProject(options: InitOptions): Promise<InitOutcome> {
  const root = path.resolve(options.root);
  const detection = await detectProject(root);
  const created: string[] = [];
  const kept: string[] = [];
  const notes: string[] = [];
  const configFile = path.join(root, detection.existingConfig ?? PROJECT_CONFIG_FILES[0]);
  if (detection.existingConfig && !options.force) {
    kept.push(detection.existingConfig);
    notes.push(`${detection.existingConfig} already exists: kept (use --force to regenerate it)`);
  } else {
    await writeFile(configFile, renderProjectConfig(detection, options.baseUrl), 'utf8');
    created.push(path.relative(root, configFile));
  }
  for (const name of DIRECTORIES) {
    const directory = path.join(root, PROJECT_DIR, name);
    if (await exists(directory)) continue;
    await mkdir(directory, { recursive: true });
    await writeFile(path.join(directory, '.gitkeep'), '', 'utf8');
    created.push(path.relative(root, directory));
  }
  const reports = path.join(root, REPORTS_DIR);
  if (!(await exists(reports))) {
    await mkdir(reports, { recursive: true });
    created.push(REPORTS_DIR);
  }
  if (options.example !== false) {
    const example = path.join(root, PROJECT_DIR, 'flows', 'example.flow.yaml');
    if (await exists(example)) kept.push(path.relative(root, example));
    else {
      await writeFile(example, EXAMPLE_FLOW, 'utf8');
      created.push(path.relative(root, example));
    }
  }
  const gitignore = path.join(root, '.gitignore');
  if (detection.git || (await exists(gitignore))) {
    const current = (await exists(gitignore)) ? await readFile(gitignore, 'utf8') : '';
    if (!current.includes(`${REPORTS_DIR}/`)) {
      await writeFile(
        gitignore,
        `${current}${current.endsWith('\n') || current === '' ? '' : '\n'}\n${GITIGNORE}`,
        'utf8',
      );
      created.push('.gitignore (entries added)');
    } else kept.push('.gitignore');
  }
  if (!detection.playwright.installed)
    notes.push(
      'Playwright is not a dependency of this project: QA-Crawler uses its own (run `npx playwright install chromium` once).',
    );
  if (detection.playwright.config)
    notes.push(`playwright.config reused for baseURL / headless / viewport: ${detection.playwright.config}`);
  if (detection.openapi) notes.push(`OpenAPI contract found: ${detection.openapi} (API tests enabled)`);
  if (detection.ci.length > 0)
    notes.push(
      `CI detected (${detection.ci.join(', ')}): add \`npx qa-crawler analyze\` to a job; exit code 1 on QA failure.`,
    );
  return { detection, configFile, created, kept, notes };
}
