import type { FlowStep } from '../config/flow-schema.js';
import type { SuggestedFlowGraph, SuggestedStep } from '../dry-run/reconciliation-model.js';
import { sentenceOf, suggestedFeature } from '../dry-run/suggested-flow.js';
import { nativeComment, translateAssertions, type TranslatedAssertion } from './assertion-translation.js';
import type { FlowDefinition } from './flow-steps.js';

/**
 * LE SCÉNARIO GHERKIN D'UN FLOW DE LA MISSION (YAML) : les mêmes phrases que le dictionnaire du moteur
 * Gherkin de QA-CRAWLER relit (le .feature est exécutable par `flows: gherkin`), les groupes métier en
 * en-têtes, les assertions métier natives en phrases « Alors », les autres en commentaires explicites
 * (le flow YAML les porte, le rejeu les vérifie). Une étape qu'aucune phrase ne sait dire (sélecteur
 * CSS) reste en commentaire, comme pour un enregistrement.
 */
export interface GeneratedFeature {
  flow: string;
  fileName: string;
  content: string;
  /** Les étapes qu'aucune phrase ne sait dire (gardées en commentaire). */
  unsaid: number;
  replayOnly: string[];
}

const slug = (text: string): string =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'flow';

function labelOf(step: FlowStep, language: 'fr' | 'en'): string {
  return sentenceOf(step, language) ?? `${step.kind} (no Gherkin sentence)`;
}

function item(step: FlowStep, language: 'fr' | 'en'): SuggestedStep {
  return {
    provenance: 'ORIGINAL',
    status: 'MATCHED',
    step,
    label: labelOf(step, language),
    comment: step.kind,
  };
}

function comment(text: string): SuggestedStep {
  return { provenance: 'ORIGINAL', status: 'MATCHED', label: text, comment: text, commentOnly: true };
}

function replayOnlyLine(assertion: TranslatedAssertion): string {
  return `business assertion ${assertion.id} — replay only (declared in the flow YAML, verified by the QA-CRAWLER replay): ${assertion.description}`;
}

/** Le .feature d'un flow de la mission. */
export function generateGherkinFeature(
  definition: FlowDefinition,
  options: { language: 'fr' | 'en'; header?: string[] },
): GeneratedFeature {
  const business = translateAssertions(definition.assertions, definition.steps.length);
  const groupAt = new Map((definition.groups ?? []).map((group) => [group.steps[0] ?? 0, group]));
  const steps: SuggestedStep[] = [];
  const emit = (position: number): void => {
    for (const assertion of business.nativeAfter.get(position) ?? [])
      if (assertion.expect)
        steps.push({
          provenance: 'ORIGINAL',
          status: 'MATCHED',
          step: { kind: 'expect', expect: assertion.expect, allow: [], optional: false },
          label: assertion.description,
          comment: nativeComment(assertion),
        });
    if (position === 0)
      for (const assertion of business.replayOnly) steps.push(comment(replayOnlyLine(assertion)));
  };
  definition.steps.forEach((step, index) => {
    const group = groupAt.get(index + 1);
    if (group)
      steps.push(comment(`── group: ${group.name}${group.description ? ` — ${group.description}` : ''}`));
    steps.push(item(step, options.language));
    emit(index + 1);
  });
  emit(0);
  const graph: SuggestedFlowGraph = {
    name: definition.name,
    source: { type: 'YAML' },
    ...(definition.startAt ? { startAt: definition.startAt } : {}),
    status: 'FULLY_MATCHED',
    steps,
  };
  const content = suggestedFeature(graph, {
    language: options.language,
    header: options.header ?? [
      `Generated by QA-CRAWLER from the flow "${definition.name}"`,
      'Review before use. The safety policy still applies when it is replayed.',
    ],
  });
  return {
    flow: definition.name,
    fileName: `${slug(definition.name)}.feature`,
    content,
    unsaid: definition.steps.filter((step) => sentenceOf(step, options.language) === undefined).length,
    replayOnly: business.replayOnly.map((assertion) => assertion.id),
  };
}

/** Un .feature par flow. */
export function generateGherkinFeatures(
  definitions: readonly FlowDefinition[],
  options: { language: 'fr' | 'en' },
): GeneratedFeature[] {
  return definitions.map((definition) => generateGherkinFeature(definition, options));
}
